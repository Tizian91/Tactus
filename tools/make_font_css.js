'use strict';
/*
 * Builds css/bravura.css: the music font Bravura (fonts/Bravura.woff2, SIL Open Font License,
 * see fonts/Bravura-OFL.txt) embedded as a data: URL, so it also loads when index.html is
 * opened by double click (file://), where browsers refuse to load font files.
 *
 *   ELECTRON_RUN_AS_NODE=1 "<VS Code>/Code.exe" tools/make_font_css.js
 */
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const b64 = fs.readFileSync(path.join(root, 'fonts', 'Bravura.woff2')).toString('base64');
fs.writeFileSync(path.join(root, 'css', 'bravura.css'),
  '/* Generated by tools/make_font_css.js - Bravura (c) Steinberg Media Technologies GmbH, SIL Open Font License 1.1 (fonts/Bravura-OFL.txt) */\n' +
  `@font-face { font-family: "Bravura"; src: url(data:font/woff2;base64,${b64}) format("woff2"); font-display: block; }\n`);
